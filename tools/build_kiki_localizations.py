#!/usr/bin/env python3
"""Build reviewed KikiTalk strings and check keys and format argument contracts."""
from pathlib import Path
import argparse, collections, json, re, sys

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'localization/catalog'
RESOURCES = ROOT / 'ios/KikiTalk/Resources'
FORMAT = re.compile(r'%(?:(\d+)\$)?[-+ #0]*(?:\d+|\*)?(?:\.(?:\d+|\*))?(hh|ll|[hlLzjt])?([@diuoxXfFeEgGaAcCsSp])')

def arguments(text):
    result = collections.Counter()
    index = 1
    for match in FORMAT.finditer(text.replace('%%', '')):
        position = int(match[1]) if match[1] else index
        result[(position, (match[2] or '') + match[3])] += 1
        if not match[1]: index += 1
    return result

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    format_keys = set()
    for source in (ROOT/'ios/KikiTalk/Sources').rglob('*.swift'):
        for match in re.finditer(r'KikiL10n\.format\("((?:\\.|[^"\\])*)"', source.read_text()):
            format_keys.add(json.loads('"' + match[1] + '"'))
    merged, origins, conflicts = {}, {}, {}
    for path in sorted(CATALOG.glob('*.json')):
        for key, entry in json.loads(path.read_text()).items():
            item = entry if isinstance(entry, dict) else {'zh-Hans': key, 'en': entry}
            if not all(isinstance(item.get(lang), str) and item[lang] for lang in ('zh-Hans', 'en')):
                raise SystemExit(f'{path.name}: missing translation for {key!r}')
            if key in format_keys and arguments(item['zh-Hans']) != arguments(item['en']):
                raise SystemExit(f'{path.name}: incompatible format arguments for {key!r}')
            if key in merged and merged[key] != item:
                conflicts.setdefault(key, []).append((origins[key], merged[key], path.name, item))
            merged[key], origins[key] = item, path.name
    override_path = ROOT / 'localization/overrides.json'
    overrides = json.loads(override_path.read_text()) if override_path.exists() else {}
    unresolved = set(conflicts) - set(overrides)
    if unresolved:
        for key in sorted(unresolved):
            print(json.dumps({'key':key,'variants':conflicts[key]},ensure_ascii=False))
        raise SystemExit('Review duplicate translations in localization/overrides.json')
    for key, entry in overrides.items():
        if key not in merged: raise SystemExit(f'Unknown override {key!r}')
        item = entry if isinstance(entry, dict) else {'zh-Hans':key,'en':entry}
        if key in format_keys and arguments(item['zh-Hans']) != arguments(item['en']): raise SystemExit(f'Invalid override format: {key}')
        if 'en.one' in item and arguments(item['en']) != arguments(item['en.one']): raise SystemExit(f'Invalid singular format: {key}')
        merged[key] = item
    missing = []
    pattern = re.compile(r'KikiL10n\.(?:text|format)\("((?:\\.|[^"\\])*)"')
    for path in sorted((ROOT/'ios/KikiTalk/Sources').rglob('*.swift')):
        for match in pattern.finditer(path.read_text()):
            key = json.loads('"' + match[1] + '"')
            if key not in merged: missing.append(f'{path.relative_to(ROOT)}: {key}')
    if missing: raise SystemExit('Missing catalog keys:\n'+'\n'.join(missing))
    outputs = {}
    for language in ('zh-Hans', 'en'):
        lines = ['/* Generated by tools/build_kiki_localizations.py. Edit localization/catalog/*.json. */']
        lines += [f'{json.dumps(key,ensure_ascii=False)} = {json.dumps(merged[key][language],ensure_ascii=False)};' for key in sorted(merged)]
        if language == 'en':
            lines += [f'{json.dumps(key + ".__one",ensure_ascii=False)} = {json.dumps(merged[key]["en.one"],ensure_ascii=False)};' for key in sorted(merged) if 'en.one' in merged[key]]
        outputs[RESOURCES/(language+'.lproj')/'Localizable.strings'] = '\n'.join(lines)+'\n'
    native = json.loads((ROOT/'localization/native_info.json').read_text())
    for language, values in native.items():
        outputs[RESOURCES/(language+'.lproj')/'InfoPlist.strings'] = '\n'.join(f'{json.dumps(k)} = {json.dumps(v,ensure_ascii=False)};' for k,v in values.items())+'\n'
        outputs[RESOURCES/(language+'.lproj')/'KikiLaunchScreen.strings'] = '"Kiki-Launch-Title.text" = '+json.dumps(values['CFBundleDisplayName'])+';\n'
    stale=[]
    for path,text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text()!=text: stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
    if stale: raise SystemExit('Stale localized resources: '+', '.join(stale))
    print(f'{"Verified" if args.check else "Built"} {len(merged)} bilingual keys and {len(outputs)} native resources; format arguments match')

if __name__=='__main__':main()
