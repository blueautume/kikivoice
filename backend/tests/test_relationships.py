def instant(value):
    return datetime.fromisoformat(value.replace("Z", "+00:00"))


@pytest.mark.parametrize("value,expected", [
    ("1900-01-01T12:00:00Z", -3.6623320178390935),
    ("2000-01-01T12:00:00Z", -3.3012588023605938),
    ("2026-02-11T12:00:00Z", -14.226179863880096),
    ("2026-06-21T12:00:00Z", -1.8242799980127842),
    ("2026-11-03T12:00:00Z", 16.492216222893628),
    ("2100-12-31T12:00:00Z", -2.8263164284887217),
])
def test_noaa_independent_javascript_reference_values(value, expected):
    # Same pinned, independently obtained official NOAA outputs as the read-only
    # reference project, not outputs generated by this Python implementation.
    assert engine.equation_of_time(instant(value)) == pytest.approx(expected, abs=1e-7)


def test_apparent_clock_crosses_midnight_without_changing_physical_term_year_month():
    birth = instant("2026-01-02T01:00:00+08:00")
    clock = engine.apparent_clock(birth, 75)
    assert (clock - instant("2026-01-01T21:56:20Z")).total_seconds() == pytest.approx(.10275, abs=.01)
    west, east = engine.four_pillars(birth, 75), engine.four_pillars(birth, 120)
    assert west[2:] == ["乙亥", "丁亥"]
    assert east[2:] == ["丙子", "戊子"]
    assert west[:2] == east[:2]
    assert engine.four_pillars(birth.astimezone(timezone.utc), 75) == west


