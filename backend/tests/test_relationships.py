@pytest.mark.parametrize("end_session,expected", [(False, 409), (True, 401)])
def test_profile_or_authorization_change_during_calculation_never_publishes_old_result(bridge_client, monkeypatch, end_session, expected):
    c = bridge_client
    a, b = login(c), login(c, "bob")
    setup_room(c, [a, b])
    for user in (a, b):
        assert c.patch("/v1/me/relationship-profile", headers=authorization(user), json=PROFILE).status_code == 200
    original = engine.room_pair
    def mutate_then_calculate(*args):
        with database(c.settings) as db:
            if end_session:
                db.execute("DELETE FROM sessions WHERE account_id=(SELECT account_id FROM accounts WHERE login_id=?)", (a["user"]["id"],))
            else:
                db.execute("UPDATE relationship_profiles SET revision=revision+1 WHERE account_id=(SELECT account_id FROM accounts WHERE login_id=?)", (b["user"]["id"],))
        return original(*args)
    monkeypatch.setattr(engine, "room_pair", mutate_then_calculate)
    response = c.get(f"/v1/voice/rooms/{ROOM}/relations", headers=authorization(a))
    assert response.status_code == expected
    assert "pairs" not in response.json()


